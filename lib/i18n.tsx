export type DictKey = keyof typeof dict.ar;

type LanguageContextValue = {
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: (key: DictKey) => string;
};

const LanguageContext = createContext<LanguageContextValue>({
  locale: 'ar',
  setLocale: () => {},
  t: (key) => dict.ar[key],
});

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => {
    if (typeof window === 'undefined') return 'ar';
    return (localStorage.getItem(STORAGE_KEY) as Locale) === 'en' ? 'en' : 'ar';
  });

  useEffect(() => {
    localStorage.setItem(STORAGE_KEY, locale);
    document.documentElement.lang = locale;
    document.documentElement.dir = locale === 'ar' ? 'rtl' : 'ltr';
  }, [locale]);

  const value: LanguageContextValue = {
    locale,
    setLocale: setLocaleState,
    t: (key) => dict[locale][key] ?? dict.ar[key],
  };
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  return useContext(LanguageContext);
}

export function typeLabel(type: SessionTypeValue, locale: Locale): string {
  const key: DictKey = type === 'واجب' ? 'type.homework' : type === 'مراجعة' ? 'type.review' : 'type.study';
  return dict[locale][key];
}
